export function isAnswered(q: Question, a: Answers): boolean {
  const v = a[q.id]
  if (q.type === 'multi') return Array.isArray(v)
  if (q.type === 'bool') return typeof v === 'boolean'
  return typeof v === 'string' && v !== ''
}
